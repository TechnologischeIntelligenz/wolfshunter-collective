import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationDirectory = path.join(projectRoot, "prisma/migrations/20260918060000_postgresql_baseline");
const migrationPath = path.join(migrationDirectory, "migration.sql");
const mode = process.argv[2] ?? "--check";
assert(["--check", "--write"].includes(mode), "Use --check or --write (initial creation only).");

// Only the datamodel is read. This placeholder deliberately overrides the old
// SQLite DATABASE_URL in .env; no real database or credentials are needed.
const result = spawnSync(process.execPath, [
  path.join(projectRoot, "node_modules/prisma/build/index.js"),
  "migrate", "diff", "--from-empty", "--to-schema-datamodel",
  "prisma/schema.prisma", "--script",
], {
  cwd: projectRoot,
  env: { ...process.env, DATABASE_URL: "postgresql://schema:unused@127.0.0.1:5432/schema_only" },
  encoding: "utf8",
  windowsHide: true,
});
if (result.error) throw result.error;
assert.equal(result.status, 0, `Prisma schema generation failed: ${result.stderr}`);
const schemaSql = result.stdout.replace(/\r\n/g, "\n").trim().replace(
  '-- CreateSchema\nCREATE SCHEMA IF NOT EXISTS "public";',
  '-- The existing public schema is provisioned by PostgreSQL/Supabase.\n-- The app owns its tables and does not need permission to create schemas.',
);
const tableNames = [...schemaSql.matchAll(/^CREATE TABLE "([A-Za-z][A-Za-z0-9_]*)"/gm)].map((match) => match[1]);
assert(tableNames.length > 0, "Prisma produced no application tables.");
const tableList = [...tableNames, "_prisma_migrations"].map((name) => `'${name}'`).join(", ");

// No browser/Data API policies are created: Shopify authentication and shop
// scoping run on the server. The owner can migrate/import; a separate runtime
// role needs explicit grants and role-specific RLS policies before use.
const accessSql = `-- Private application tables: prevent Supabase Data API exposure.
-- Guard optional roles so the same baseline works on ordinary PostgreSQL.
DO $private_application_tables$
DECLARE
  application_table text;
  application_sequence text;
  api_role text;
BEGIN
  FOREACH application_table IN ARRAY ARRAY[${tableList}]
  LOOP
    IF to_regclass(format('public.%I', application_table)) IS NULL THEN
      IF application_table = '_prisma_migrations' THEN
        CONTINUE;
      END IF;
      RAISE EXCEPTION 'Missing application table: %', application_table;
    END IF;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', application_table);
    EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC', application_table);
    FOR api_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role')
    LOOP
      EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM %I', application_table, api_role);
    END LOOP;
    FOR application_sequence IN
      SELECT pg_get_serial_sequence(format('public.%I', application_table), column_name)
      FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = application_table
        AND pg_get_serial_sequence(format('public.%I', application_table), column_name) IS NOT NULL
    LOOP
      EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC', application_sequence);
      FOR api_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role')
      LOOP
        EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM %I', application_sequence, api_role);
      END LOOP;
    END LOOP;
  END LOOP;
END
$private_application_tables$;`;

const migrationSql = `-- PostgreSQL baseline for a NEW, EMPTY application database.
-- Generated by scripts/prepare-postgresql-baseline.mjs with installed Prisma.
-- SQLite history is preserved in prisma/sqlite-migrations-archive.
-- Do not edit or regenerate after this migration has been applied.
BEGIN;
SET LOCAL search_path TO public;

${schemaSql}

${accessSql}

COMMIT;
`;

if (mode === "--write") {
  assert(!existsSync(migrationPath), "Baseline already exists. Never overwrite an applied migration.");
  mkdirSync(migrationDirectory, { recursive: true });
  writeFileSync(migrationPath, migrationSql, { encoding: "utf8", flag: "wx" });
  const lockPath = path.join(projectRoot, "prisma/migrations/migration_lock.toml");
  if (!existsSync(lockPath)) writeFileSync(lockPath, 'provider = "postgresql"\n', { flag: "wx" });
  console.log(`Created PostgreSQL baseline for ${tableNames.length} private application tables.`);
} else {
  assert.equal(readFileSync(migrationPath, "utf8").replace(/\r\n/g, "\n"), migrationSql,
    "Baseline differs from current schema/security generation. Create a new migration once applied.");
  assert.match(readFileSync(path.join(projectRoot, "prisma/migrations/migration_lock.toml"), "utf8"),
    /provider\s*=\s*"postgresql"/);
  console.log(`PostgreSQL baseline matches all ${tableNames.length} models and private-table controls.`);
}
